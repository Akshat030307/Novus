/**
 * The syllabus-plan function as one self-contained file, for pasting into the
 * Supabase dashboard's function editor (which is simplest with a single file).
 *
 * Generated from supabase/functions/syllabus-plan/index.ts with the shared
 * spec inlined, so the pasted copy cannot drift from the source of truth:
 *
 *   node tools/build-edge-single.mjs   ->  deploy/syllabus-plan.single.ts
 *
 * With the Supabase CLI none of this is needed: `supabase functions deploy
 * syllabus-plan` bundles the shared file itself.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fn = readFileSync(root + '/supabase/functions/syllabus-plan/index.ts', 'utf8')
const spec = readFileSync(root + '/supabase/functions/_shared/syllabus-spec.js', 'utf8').replace(/^export /gm, '')
const line = /^import \{[^}]+\} from '\.\.\/_shared\/syllabus-spec\.js'\n/m
if (!line.test(fn)) throw new Error('the shared import line moved; update this script')
const out =
  '// GENERATED by tools/build-edge-single.mjs: edit supabase/functions/ instead.\n' +
  '// @ts-nocheck  (the source is type-checked; this paste-copy inlines plain JS)\n' +
  fn.replace(line, '\n// ---- inlined from supabase/functions/_shared/syllabus-spec.js ----\n' + spec + '// ---- end of shared spec ----\n\n')
writeFileSync(root + '/deploy/syllabus-plan.single.ts', out)
console.log('wrote deploy/syllabus-plan.single.ts')
